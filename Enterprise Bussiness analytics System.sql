-- Enterprise Business Analytics System
CREATE DATABASE enterprise_bussiness;
USE enterprise_bussiness;
SET FOREIGN_KEY_CHECKS=0;


SET FOREIGN_KEY_CHECKS=1;

CREATE TABLE dim_date (date_key INT PRIMARY KEY,full_date DATE,day INT,month INT,month_name VARCHAR(20),quarter VARCHAR(5),year INT,week_number INT,day_name VARCHAR(20),is_weekend BOOLEAN);
CREATE TABLE dim_customer (customer_id INT PRIMARY KEY,customer_name VARCHAR(100),gender VARCHAR(20),date_of_birth DATE,city VARCHAR(50),state VARCHAR(50),country VARCHAR(50),signup_date DATE,customer_segment VARCHAR(20),income_band VARCHAR(20));
CREATE TABLE dim_category (category_id INT PRIMARY KEY,category_name VARCHAR(50),department VARCHAR(50));
CREATE TABLE dim_supplier (supplier_id INT PRIMARY KEY,supplier_name VARCHAR(100),city VARCHAR(50),state VARCHAR(50),country VARCHAR(50),supplier_rating DECIMAL(3,1),lead_time_days INT,supplier_status VARCHAR(20));
CREATE TABLE dim_product (product_id INT PRIMARY KEY,product_name VARCHAR(100),category_id INT,supplier_id INT,brand VARCHAR(50),cost_price DECIMAL(10,2),selling_price DECIMAL(10,2),launch_date DATE,product_status VARCHAR(20),FOREIGN KEY(category_id) REFERENCES dim_category(category_id),FOREIGN KEY(supplier_id) REFERENCES dim_supplier(supplier_id));
CREATE TABLE dim_store (store_id INT PRIMARY KEY,store_name VARCHAR(100),city VARCHAR(50),state VARCHAR(50),country VARCHAR(50),region VARCHAR(30),store_type VARCHAR(30),opening_date DATE,store_status VARCHAR(20));
CREATE TABLE dim_employee (employee_id INT PRIMARY KEY,employee_name VARCHAR(100),store_id INT,job_role VARCHAR(50),joining_date DATE,salary_band VARCHAR(20),employment_status VARCHAR(20),FOREIGN KEY(store_id) REFERENCES dim_store(store_id));
CREATE TABLE dim_campaign (campaign_id INT PRIMARY KEY,campaign_name VARCHAR(100),channel VARCHAR(30),campaign_type VARCHAR(30),start_date DATE,end_date DATE,budget DECIMAL(12,2),target_segment VARCHAR(30));
CREATE TABLE fact_sales (sales_id INT PRIMARY KEY,order_date DATE,customer_id INT,product_id INT,store_id INT,employee_id INT,quantity INT,unit_price DECIMAL(10,2),discount DECIMAL(10,2),cost DECIMAL(10,2),payment_method VARCHAR(30),order_status VARCHAR(20),FOREIGN KEY(customer_id) REFERENCES dim_customer(customer_id),FOREIGN KEY(product_id) REFERENCES dim_product(product_id),FOREIGN KEY(store_id) REFERENCES dim_store(store_id),FOREIGN KEY(employee_id) REFERENCES dim_employee(employee_id));
CREATE TABLE fact_returns (return_id INT PRIMARY KEY,sales_id INT,return_date DATE,product_id INT,customer_id INT,return_quantity INT,return_reason VARCHAR(50),refund_amount DECIMAL(10,2),FOREIGN KEY(sales_id) REFERENCES fact_sales(sales_id),FOREIGN KEY(product_id) REFERENCES dim_product(product_id),FOREIGN KEY(customer_id) REFERENCES dim_customer(customer_id));
CREATE TABLE fact_inventory (inventory_id INT PRIMARY KEY,inventory_date DATE,product_id INT,store_id INT,opening_stock INT,received_stock INT,sold_quantity INT,closing_stock INT,damaged_quantity INT,FOREIGN KEY(product_id) REFERENCES dim_product(product_id),FOREIGN KEY(store_id) REFERENCES dim_store(store_id));
CREATE TABLE fact_payments (payment_id INT PRIMARY KEY,sales_id INT,payment_date DATE,payment_method VARCHAR(30),payment_amount DECIMAL(10,2),payment_status VARCHAR(20),transaction_fee DECIMAL(10,2),FOREIGN KEY(sales_id) REFERENCES fact_sales(sales_id));
CREATE TABLE fact_marketing (marketing_id INT PRIMARY KEY,campaign_id INT,customer_id INT,campaign_date DATE,impressions INT,clicks INT,leads INT,conversion INT,acquisition_cost DECIMAL(10,2),revenue_generated DECIMAL(12,2),FOREIGN KEY(campaign_id) REFERENCES dim_campaign(campaign_id),FOREIGN KEY(customer_id) REFERENCES dim_customer(customer_id));

