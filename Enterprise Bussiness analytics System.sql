-- Project Insights

-- Total Revenue, Orders, and Average Order Value (AOV)

SELECT COUNT(sales_id) AS total_orders,
SUM((quantity * unit_price) - discount) AS gross_revenue,
ROUND(AVG((quantity * unit_price) - discount), 2) AS average_order_value
FROM fact_sales;

-- Total Marketing Spend vs. Total Revenue Generated

SELECT 
    SUM(acquisition_cost) AS total_marketing_spend,
    SUM(revenue_generated) AS total_marketing_revenue,
    ROUND(SUM(revenue_generated) / SUM(acquisition_cost), 2) AS overall_roas
FROM fact_marketing;

-- Revenue Generated by Payment Method

SELECT 
    payment_method,
    COUNT(payment_id) AS transaction_count,
    SUM(payment_amount) AS total_collected
FROM fact_payments
WHERE payment_status = 'Paid'
GROUP BY payment_method
ORDER BY total_collected DESC;


-- Count of Successful vs. Cancelled Payments

SELECT 
    payment_status,
    COUNT(payment_id) AS total_transactions
FROM fact_payments
GROUP BY payment_status;


-- Overall Product Return Rate

SELECT 
    COUNT(DISTINCT s.sales_id) AS total_sales_count,
    COUNT(DISTINCT r.return_id) AS total_returns_count,
    ROUND((COUNT(DISTINCT r.return_id) * 100.0 / COUNT(DISTINCT s.sales_id)), 2) AS return_rate_percentage
FROM fact_sales s
LEFT JOIN fact_returns r ON s.sales_id = r.sales_id;

-- Product Category Performance

SELECT 
    c.category_name,
    COUNT(s.sales_id) AS total_orders_sold,
    SUM(s.quantity) AS total_units_sold,
    SUM((s.quantity * s.unit_price) - s.discount) AS category_revenue
FROM fact_sales s
JOIN dim_product d 
ON s.product_id = d.product_id
JOIN dim_category c
ON d.category_id=c.category_id
GROUP BY c.category_name
ORDER BY category_revenue DESC;





